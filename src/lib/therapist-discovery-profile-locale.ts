export type TherapistDiscoveryProfileMessageKey = keyof typeof messages['en-IN'];

export function therapistDiscoveryProfileMessage(locale: SupportedLocale, key: TherapistDiscoveryProfileMessageKey): string {
  return messages[locale]?.[key] ?? messages['en-IN'][key];
}

export function therapistDiscoveryVerificationLabel(locale: SupportedLocale, status: TherapistVerificationStatus): string {
  if (locale === 'hi-IN') return status === 'unverified' ? 'असत्यापित' : status === 'pending' ? 'समीक्षा लंबित' : status === 'verified' ? 'सत्यापित' : 'सत्यापन असफल';
  if (locale === 'gu-IN') return status === 'unverified' ? 'અચકાસાયેલ' : status === 'pending' ? 'સમીક્ષા બાકી' : status === 'verified' ? 'ચકાસાયેલ' : 'ચકાસણી નિષ્ફળ';
  return status === 'unverified' ? 'Unverified' : status === 'pending' ? 'Pending review' : status === 'verified' ? 'Verified' : 'Verification unsuccessful';
}

export function therapistDiscoveryServiceModeLabel(locale: SupportedLocale, mode: TherapistServiceMode): string {
  if (locale === 'hi-IN') return mode === 'home_visit' ? 'होम विज़िट' : mode === 'telephysiotherapy' ? 'टेलीफिजियोथेरेपी' : 'क्लिनिक विज़िट';
  if (locale === 'gu-IN') return mode === 'home_visit' ? 'હોમ વિઝિટ' : mode === 'telephysiotherapy' ? 'ટેલિફિઝિયોથેરાપી' : 'ક્લિનિક વિઝિટ';
  return mode === 'home_visit' ? 'Home visit' : mode === 'telephysiotherapy' ? 'Telephysiotherapy' : 'Clinic visit';
}
